// Builds the whole site into dist/ from Begad's product feed.
//
//   node tools/build.mjs            fetch the feed, refresh details, build
//   node tools/build.mjs --offline  build from catalog.js and data/details.json only
//
// Writes, in the repository: catalog.js (the feed snapshot the pages paint
// first) and data/details.json (each product's description and photos from
// Begad's product endpoint, refreshed a few at a time). Writes, in dist/:
// one page per URL (home, departments, categories, products, deals, search,
// wholesale, 404), sitemap.xml, robots.txt and the static files.
import { readFile, writeFile, mkdir, rm, cp } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import vm from 'node:vm';
import {
  SITE, CATALOG_API, DEPARTMENTS, PAGE_SIZE, buildCatalog, deptCounts, deptNavHtml, homeHtml, listingHtml,
  listingTitle, productHtml, wholesaleHtml, notFoundHtml, productJsonLd, deptHref, subHref, productHref, esc,
  money, discountOf, guidesIndexHtml, guideHtml, guideJsonLd, guideHref, guidesIndexHref
} from '../site.js';

const ROOT = new URL('../', import.meta.url);
const DIST = new URL('../dist/', import.meta.url);
const OFFLINE = process.argv.includes('--offline');
const MIN_ITEMS = 20; // fewer means the feed is broken, not that the range shrank
const DETAIL_REFRESH_PER_RUN = 40; // older details refetched per run (a full pass every ~1.5 days)
const DETAIL_MAX_AGE_MS = 3 * 24 * 3600 * 1000;

// ---------------------------------------------------------------- feed

async function readSnapshot() {
  const src = await readFile(new URL('catalog.js', ROOT), 'utf8');
  const ctx = {};
  vm.runInNewContext(`${src}\nthis.items = catalogProducts;`, ctx);
  return ctx.items;
}

async function fetchFeed() {
  const res = await fetch(CATALOG_API, { headers: { Accept: 'application/json' } });
  if (!res.ok) throw new Error(`Begad feed answered HTTP ${res.status}`);
  const data = await res.json();
  if (!data.ok || !Array.isArray(data.items) || data.items.length < MIN_ITEMS) {
    throw new Error(`Begad feed looks wrong (${data.items ? data.items.length : 'no'} items)`);
  }
  return data.items.map(item => ({
    id: item.id,
    sku: item.sku,
    name: item.name,
    category: item.category,
    url: item.url,
    thumb: item.thumb,
    image: item.image,
    price: {
      amount: item.price.amount,
      amount_with_tax: item.price.amount_with_tax,
      compare_at_amount: item.price.compare_at_amount
    },
    in_stock: item.in_stock
  }));
}

let items;
if (OFFLINE) {
  items = await readSnapshot();
} else {
  try {
    items = await fetchFeed();
    const header = `// Snapshot of Begad's VIDVIE product list. Generated by tools/build.mjs
// from ${CATALOG_API}
// Do not edit by hand: products, names, photos, prices and stock are managed
// on Begad.ae, and app.js replaces this list with the live one on every visit.
`;
    await writeFile(new URL('catalog.js', ROOT), `${header}const catalogProducts = ${JSON.stringify(items, null, 1)};\n`);
  } catch (err) {
    console.warn(`Feed unavailable (${err.message}); building from the catalog.js snapshot`);
    items = await readSnapshot();
  }
}

const products = buildCatalog(items);
const built = new Set(products.map(p => p.id));

// ---------------------------------------------------------------- details

const detailsFile = new URL('data/details.json', ROOT);
let details = {};
try { details = JSON.parse(await readFile(detailsFile, 'utf8')); } catch { details = {}; }

function cleanDetail(item) {
  const text = s => String(s || '').replace(/<[^>]*>/g, ' ').replace(/&nbsp;/g, ' ').replace(/[ \t]+/g, ' ').trim();
  return {
    fetched: Date.now(),
    description: text(item.description).slice(0, 4000),
    short_description: text(item.short_description).slice(0, 600),
    images: (item.images || []).filter(u => /^https:\/\//.test(u)).slice(0, 8),
    warranty: text(item.policies && item.policies.warranty_summary),
    returns: text(item.policies && item.policies.return_summary)
  };
}

if (!OFFLINE) {
  const missing = products.filter(p => !details[p.id]);
  const stale = products.filter(p => details[p.id] && Date.now() - details[p.id].fetched > DETAIL_MAX_AGE_MS)
    .sort((a, b) => details[a.id].fetched - details[b.id].fetched).slice(0, DETAIL_REFRESH_PER_RUN);
  let ok = 0;
  for (const p of [...missing, ...stale]) {
    try {
      const res = await fetch(`https://begad.ae/api/agent/products/${p.id}`, { headers: { Accept: 'application/json' } });
      if (!res.ok) continue;
      const data = await res.json();
      if (data && data.ok && data.item) { details[p.id] = cleanDetail(data.item); ok++; }
    } catch { /* keep the old copy */ }
    await new Promise(r => setTimeout(r, 150));
  }
  // Forget products Begad no longer lists
  Object.keys(details).forEach(id => { if (!built.has(Number(id))) delete details[id]; });
  await mkdir(new URL('data/', ROOT), { recursive: true });
  const sorted = Object.fromEntries(Object.keys(details).sort().map(k => [k, details[k]]));
  await writeFile(detailsFile, `${JSON.stringify(sorted, null, 1)}\n`);
  console.log(`details: ${ok} fetched, ${Object.keys(details).length} kept`);
}

// ---------------------------------------------------------------- guides

// Buying guides written by Begad's daily office job (begad.ae
// app/seo_articles.php). Kept in data/articles.json so a build works when
// Begad cannot be reached, and so the 6-hourly sync sees a new guide as a change.
const ARTICLES_API = 'https://begad.ae/api/seo-articles/v1/public?site=vidvie';
const articlesFile = new URL('data/articles.json', ROOT);
let articles = [];
try { articles = JSON.parse(await readFile(articlesFile, 'utf8')); } catch { articles = []; }
articles.forEach(a => { a.lang = a.lang === 'ar' ? 'ar' : 'en'; }); // copies saved before Arabic existed
if (!OFFLINE) {
  try {
    const res = await fetch(ARTICLES_API, { headers: { Accept: 'application/json' } });
    const data = res.ok ? await res.json() : null;
    if (data && data.ok && Array.isArray(data.articles)) {
      articles = data.articles.map(a => ({
        id: Number(a.id), lang: a.lang === 'ar' ? 'ar' : 'en', slug: a.slug, title: a.title, meta_description: a.meta_description,
        word_count: Number(a.word_count) || 0, topic_key: a.topic_key,
        primary_keyword: a.primary_keyword, product_ids: a.product_ids, published_at: a.published_at,
        updated_at: a.updated_at, body: a.body
      })).filter(a => /^[a-z0-9-]+$/.test(a.slug || ''));
      await mkdir(new URL('data/', ROOT), { recursive: true });
      await writeFile(articlesFile, `${JSON.stringify(articles, null, 1)}\n`);
    } else {
      console.warn(`Guides unavailable (HTTP ${res.status}); using data/articles.json`);
    }
  } catch (err) {
    console.warn(`Guides unavailable (${err.message}); using data/articles.json`);
  }
}

// ---------------------------------------------------------------- pages

const template = await readFile(new URL('template.html', ROOT), 'utf8');
const version = createHash('sha1').update(await readFile(new URL('app.js', ROOT)))
  .update(await readFile(new URL('site.js', ROOT))).update(await readFile(new URL('styles.css', ROOT))).digest('hex').slice(0, 10);
const counts = deptCounts(products);
const liveDepts = DEPARTMENTS.filter(d => counts[d.slug]);
const footDepts = liveDepts.map(d => `<li><a href="${deptHref(d.slug)}">${esc(d.name)}</a></li>`).join('') +
  '<li><a href="/deals/">Deals</a></li>';
const ogDefault = `${SITE}/assets/og-image.jpg`;
const orgLd = {
  '@context': 'https://schema.org',
  '@graph': [
    { '@type': 'Organization', '@id': `${SITE}/#org`, name: 'VIDVIE UAE', url: `${SITE}/`, logo: `${SITE}/assets/vidvie-official-logo.png`,
      contactPoint: { '@type': 'ContactPoint', telephone: '+97148356358', email: 'contact@begad.ae', contactType: 'customer service', areaServed: 'AE' } },
    { '@type': 'WebSite', '@id': `${SITE}/#site`, url: `${SITE}/`, name: 'VIDVIE UAE', publisher: { '@id': `${SITE}/#org` },
      potentialAction: { '@type': 'SearchAction', target: `${SITE}/search/?q={search_term_string}`, 'query-input': 'required name=search_term_string' } }
  ]
};

const pages = []; // { path, priority } for the sitemap

async function writePage(path, { title, desc, content, page, nav = '', jsonLd = orgLd, ogImage = ogDefault, ogType = 'website', noindex = false, file, lang = 'en', alternates = [] }) {
  const html = template
    .replace('<html lang="en">', `<html lang="${lang}">`)
    .replace('__HEADEXTRA__', alternates.map(([l, href]) => `<link rel="alternate" hreflang="${l}" href="${SITE}${href}" />`).join('\n    '))
    .replaceAll('__TITLE__', esc(title))
    .replaceAll('__DESC__', esc(desc))
    .replaceAll('__CANONICAL__', `${SITE}${path}`)
    .replace('__ROBOTS__', noindex ? '<meta name="robots" content="noindex, follow" />' : '')
    .replaceAll('__OGTYPE__', ogType)
    .replaceAll('__OGIMAGE__', esc(ogImage))
    .replaceAll('__VERSION__', version)
    .replace('__Q__', '')
    .replace('__JSONLD__', JSON.stringify(jsonLd).replace(/</g, '\\u003c'))
    .replace('__PAGE__', JSON.stringify(Object.assign({ nav }, page)).replace(/</g, '\\u003c'))
    .replace('__NAV__', deptNavHtml(products, nav))
    .replace('__FOOTDEPTS__', footDepts)
    .replace('__CONTENT__', () => content);
  const target = new URL(file || `.${path}index.html`, DIST);
  await mkdir(new URL('./', target), { recursive: true });
  await writeFile(target, html);
}

const listOpts = { sort: '', min: 0, max: 0, stock: false, sale: false, limit: PAGE_SIZE };
const plural = n => `${n} product${n === 1 ? '' : 's'}`;

await rm(DIST, { recursive: true, force: true });
await mkdir(DIST, { recursive: true });

// Home
await writePage('/', {
  title: 'VIDVIE UAE | Official VIDVIE store in the UAE: chargers, power banks, earbuds',
  desc: `Shop all ${products.length} VIDVIE products in the UAE: power banks, GaN chargers, cables, earbuds, headphones, speakers and smart watches. Shipped from Dubai with a 12-month local warranty.`,
  content: homeHtml(products, built), page: { type: 'home' }
});
pages.push({ path: '/', priority: '1.0' });

// All products, deals, search, wholesale
await writePage('/products/', {
  title: 'All VIDVIE products | VIDVIE UAE',
  desc: `Browse all ${products.length} VIDVIE products available in the UAE, with prices in AED including VAT.`,
  content: listingHtml(products, { kind: 'all' }, listOpts, built), page: { type: 'listing', view: { kind: 'all' } }, nav: 'all'
});
pages.push({ path: '/products/', priority: '0.9' });

const dealCount = products.filter(p => discountOf(p) > 0).length;
await writePage('/deals/', {
  title: 'VIDVIE deals and offers in the UAE | VIDVIE UAE',
  desc: `${plural(dealCount)} on sale: VIDVIE chargers, power banks, audio and accessories at reduced prices in the UAE.`,
  content: listingHtml(products, { kind: 'deals' }, listOpts, built), page: { type: 'listing', view: { kind: 'deals' } }, nav: 'deals'
});
pages.push({ path: '/deals/', priority: '0.8' });

await writePage('/search/', {
  title: 'Search | VIDVIE UAE', desc: 'Search the VIDVIE UAE catalogue.', noindex: true,
  content: listingHtml(products, { kind: 'search', q: '' }, listOpts, built), page: { type: 'listing', view: { kind: 'search' } }
});

await writePage('/wholesale/', {
  title: 'VIDVIE wholesale in the UAE | VIDVIE UAE',
  desc: 'Wholesale VIDVIE supply for retailers, telecom stores, corporate gifts and resellers in the UAE, with stock in Dubai.',
  content: wholesaleHtml(), page: { type: 'wholesale' }, nav: 'wholesale'
});
pages.push({ path: '/wholesale/', priority: '0.5' });

// Departments and their categories
for (const d of liveDepts) {
  const n = counts[d.slug].total;
  const subNames = d.subs.filter(s => counts[d.slug].subs[s[0]]).map(s => s[1]);
  await writePage(deptHref(d.slug), {
    title: `VIDVIE ${d.name} in the UAE | VIDVIE UAE`,
    desc: `Shop ${plural(n)} of VIDVIE ${d.name.toLowerCase()}${subNames.length > 1 ? `: ${subNames.join(', ').toLowerCase()}` : ''}. Prices in AED, shipped from Dubai.`,
    content: listingHtml(products, { kind: 'dept', dept: d.slug }, listOpts, built),
    page: { type: 'listing', view: { kind: 'dept', dept: d.slug } }, nav: d.slug
  });
  pages.push({ path: deptHref(d.slug), priority: '0.8' });
  if (d.subs.length < 2) continue;
  for (const [slug, name] of d.subs) {
    const m = counts[d.slug].subs[slug];
    if (!m) continue;
    const view = { kind: 'dept', dept: d.slug, sub: slug };
    await writePage(subHref(d.slug, slug), {
      title: `${listingTitle(view)} in the UAE | VIDVIE UAE`,
      desc: `Shop ${plural(m)} of VIDVIE ${name.toLowerCase()} in the UAE. Prices in AED including VAT, shipped from Dubai with a 12-month warranty.`,
      content: listingHtml(products, view, listOpts, built), page: { type: 'listing', view }, nav: d.slug
    });
    pages.push({ path: subHref(d.slug, slug), priority: '0.7' });
  }
}

// Products
for (const p of products) {
  const det = details[p.id] || null;
  const summary = (det && (det.short_description || det.description)) || '';
  const desc = summary
    ? `${summary.slice(0, 150).replace(/\s+\S*$/, '')}… AED ${money(p.price)} in the UAE.`
    : `${p.name}. AED ${money(p.price)} including VAT, shipped from Dubai with a 12-month local warranty.`;
  const ld = productJsonLd(p, det);
  const dept = DEPARTMENTS.find(d => d.slug === p.dept);
  const crumbLd = {
    '@context': 'https://schema.org', '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Home', item: `${SITE}/` },
      { '@type': 'ListItem', position: 2, name: dept.name, item: `${SITE}${deptHref(dept.slug)}` },
      { '@type': 'ListItem', position: 3, name: p.title, item: `${SITE}${productHref(p)}` }
    ]
  };
  await writePage(productHref(p), {
    title: `${p.title.length > 70 ? `${p.title.slice(0, 68).replace(/\s+\S*$/, '')}…` : p.title} | VIDVIE UAE`,
    desc, content: productHtml(p, products, det, built),
    page: { type: 'product', productId: p.id, details: det }, nav: p.dept,
    jsonLd: [ld, crumbLd], ogImage: (det && det.images && det.images[0]) || p.image, ogType: 'product'
  });
  pages.push({ path: productHref(p), priority: p.inStock ? '0.6' : '0.3' });
}

// Guides: in the sitemap, not in the menus. English under /guides/, Arabic
// under /ar/guides/; a pair (same topic) points at each other with hreflang.
for (const lang of ['en', 'ar']) {
  const list = articles.filter(a => a.lang === lang);
  if (!list.length) continue;
  const ar = lang === 'ar';
  await writePage(guidesIndexHref(lang), {
    title: ar ? 'أدلة شراء فيدفي | VIDVIE UAE' : 'VIDVIE buying guides | VIDVIE UAE',
    desc: ar ? 'أدلة لاختيار شواحن وباور بانك وسماعات وإكسسوارات فيدفي في الإمارات.' : 'Buying guides for VIDVIE chargers, power banks, cables, audio and accessories in the UAE.',
    content: guidesIndexHtml(list, products, lang), page: { type: 'guides' }, lang
  });
  pages.push({ path: guidesIndexHref(lang), priority: '0.4' });
  for (const a of list) {
    const twin = articles.find(o => o.lang !== a.lang && o.topic_key && o.topic_key === a.topic_key);
    const firstProduct = products.find(p => (a.product_ids || []).includes(p.id));
    await writePage(guideHref(a), {
      title: `${a.title} | VIDVIE UAE`, desc: a.meta_description,
      content: guideHtml(a, products, built, list.filter(o => o.id !== a.id)),
      page: { type: 'guide', guideId: a.id }, jsonLd: guideJsonLd(a, products), lang,
      alternates: twin ? [[a.lang, guideHref(a)], [twin.lang, guideHref(twin)]] : [],
      ogImage: firstProduct ? firstProduct.image : ogDefault, ogType: 'article'
    });
    pages.push({ path: guideHref(a), priority: '0.6' });
  }
}

// 404 (CloudFront answers missing pages with it)
await writePage('/404.html', {
  title: 'Page not found | VIDVIE UAE', desc: 'This page does not exist.', noindex: true,
  content: notFoundHtml(), page: { type: 'notfound' }, file: '404.html'
});

